"""Build plugins/maxey0/app/maxey0.js: the whole dashboard (styles, markup, parser, logic, logo) as one script.

The inline widget only carries a tiny template plus the state, and loads this file from cdn.jsdelivr.net,
so a render costs a few hundred bytes of output instead of the whole dashboard.

usage: python3 build-app.py <dashboard.src.html> <parser.js> <logo.webp> <out.js>
"""
import base64, json, pathlib, re, subprocess, sys
src, parser, logo, out = map(pathlib.Path, sys.argv[1:5])
t = src.read_text()
css = re.search(r"<style>\n?(.*?)</style>", t, re.S).group(1)
body = t[t.index("</style>") + len("</style>") : t.index("<script>")].strip()
assert body.startswith('<div id="m0">') and body.endswith("</div>"), "markup must be wrapped in #m0"
inner = body[len('<div id="m0">') : -len("</div>")].replace("__LOGO__", base64.b64encode(logo.read_bytes()).decode())
js = t[t.index("<script>") + len("<script>") : t.rindex("</script>")]
assert js.count("__PARSER__") == 1 and js.count("const S=__STATE__;") == 1, "script placeholders missing"
js = js.replace("__PARSER__", "").replace("const S=__STATE__;", "const S=state||{};")
app = (
    "/* Maxey0 dashboard: generated by plugins/maxey0/tests/build-app.py from src/. Do not edit. */\n"
    "(function(){\n"
    + parser.read_text().strip() + "\n"
    + "var CSS=" + json.dumps(css) + ";\nvar HTML=" + json.dumps(inner) + ";\n"
    + "function mount(state){var root=document.getElementById(\"m0\");if(!root||root.dataset.mounted)return;root.dataset.mounted=\"1\";"
    + "root.innerHTML=\"<style>\"+CSS+\"</style>\"+HTML;\n"
    + js.strip() + "\n}\n"
    + "window.Maxey0={version:\"0.3.1\",mount:mount,parseWorkflow:parseWorkflow,stagesOf:stagesOf};\n"
    + "mount(window.MAXEY0||{});\n})();\n"
)
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(app)
subprocess.run(["node", "--check", str(out)], check=True)
print("built", out, len(app), "bytes")
